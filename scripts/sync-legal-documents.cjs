const fs = require('node:fs');
const path = require('node:path');

const assetsDirectory = path.join(__dirname, '..', 'src', 'assets');
const documentFiles = {
  userAgreement: 'user-agreement.html',
  termsOfService: 'terms-of-service.html',
  privacyPolicy: 'privacy-policy.html',
};

function syncLegalDocuments({ check = false } = {}) {
  const entries = Object.entries(documentFiles).map(([key, file]) => {
    const html = fs.readFileSync(path.join(assetsDirectory, 'legal', file), 'utf8');
    const literal = JSON.stringify(html).replace(/[<>&']/g, character =>
      `\\u${character.charCodeAt(0).toString(16).padStart(4, '0')}`);
    return `  ${key}: ${literal},`;
  });
  const generated = '// Generated from src/assets/legal/*.html. Do not edit this file directly.\n'
    + '// Run npm run legal:sync after editing the HTML; Metro also syncs on startup.\n'
    + `export const legalDocuments = {\n${entries.join('\n')}\n} as const;\n`;
  const outputPath = path.join(assetsDirectory, 'legalDocuments.ts');
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : null;
  if (current === generated) return;
  if (check) throw new Error('Bundled legal documents are out of date. Run npm run legal:sync.');
  fs.writeFileSync(outputPath, generated);
}

module.exports = syncLegalDocuments;

if (require.main === module) {
  syncLegalDocuments({ check: process.argv.includes('--check') });
  console.log('Bundled legal documents match src/assets/legal/*.html.');
}
